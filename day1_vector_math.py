import numpy as np

# Let's create two mathematical vectors
vector_A = np.array([1, 2, 3])
vector_B = np.array([4, 5, 6])

# Calculate the Dot Product: (1*4) + (2*5) + (3*6) = 4 + 10 + 18 = 32
dot_product = np.dot(vector_A, vector_B)

print("Vector A:", vector_A)
print("Vector B:", vector_B)
print("The Mathematical Dot Product is:", dot_product)
